package detect

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/zricethezav/gitleaks/v8/report"
)

func IsNew(finding report.Finding, redact uint, baseline []report.Finding) bool {
	// Explicitly testing each property as it gives significantly better performance in comparison to cmp.Equal(). Drawback is that
	// the code requires maintenance if/when the Finding struct changes
	for _, b := range baseline {
		if !baselineMetaMatches(finding, b) {
			continue
		}
		if !baselineSecretMatches(finding, b, redact) {
			continue
		}
		return false
	}
	return true
}

// baselineMetaMatches compares every non-secret property of a finding against
// a baseline entry. Line/column, file and commit metadata are always compared
// so that moved findings and SARIF locations keep their original semantics.
func baselineMetaMatches(finding report.Finding, baseline report.Finding) bool {
	return finding.RuleID == baseline.RuleID &&
		finding.Description == baseline.Description &&
		finding.StartLine == baseline.StartLine &&
		finding.EndLine == baseline.EndLine &&
		finding.StartColumn == baseline.StartColumn &&
		finding.EndColumn == baseline.EndColumn &&
		finding.File == baseline.File &&
		finding.Commit == baseline.Commit &&
		finding.Author == baseline.Author &&
		finding.Email == baseline.Email &&
		finding.Date == baseline.Date &&
		finding.Message == baseline.Message &&
		// Omit checking finding.Fingerprint - if the format of the fingerprint changes, the users will see unexpected behaviour
		finding.Entropy == baseline.Entropy
}

// baselineSecretMatches determines whether the secret value of a finding is
// covered by a baseline entry.
//
// When redaction is enabled, plaintext values are unavailable in the output,
// so the comparison prefers the pre-redaction SecretHash captured by both the
// current scan (before masking) and redacted baselines generated by gitleaks
// versions that include the hash. A rotated secret yields a different hash and
// is therefore reported as a new finding.
//
// Baselines without a SecretHash (unredacted reports, or redacted reports
// produced by older gitleaks versions) fall back to the historical behaviour:
// exact Match/Secret comparison for unredacted baselines, or skipping the
// value check when both sides are redacted.
func baselineSecretMatches(finding report.Finding, baseline report.Finding, redact uint) bool {
	if redact == 0 {
		return finding.Match == baseline.Match && finding.Secret == baseline.Secret
	}

	if finding.SecretHash != "" && baseline.SecretHash != "" {
		return finding.SecretHash == baseline.SecretHash
	}

	if isRedactedValue(finding.Secret) || isRedactedValue(baseline.Secret) {
		// At least one side is redacted and neither side carries a hash
		// (legacy behaviour): no reliable value comparison is possible, so
		// preserve the pre-hash behaviour and ignore the secret value.
		return true
	}

	// Neither side is redacted and neither side carries a hash (e.g. an
	// unredacted baseline paired with a redacted scan before the finding was
	// masked): compare the current plaintext against the stored value.
	return finding.Match == baseline.Match && finding.Secret == baseline.Secret
}

// isRedactedValue reports whether a persisted Secret/Match value was produced
// by Redact (full "REDACTED" or a partial "prefix..." mask) or by older
// gitleaks versions that used asterisk masks.
func isRedactedValue(value string) bool {
	return value == "REDACTED" ||
		strings.HasSuffix(value, "...") ||
		strings.Trim(value, "*") == ""
}

func LoadBaseline(baselinePath string) ([]report.Finding, error) {
	bytes, err := os.ReadFile(baselinePath)
	if err != nil {
		return nil, fmt.Errorf("could not open %s", baselinePath)
	}

	var previousFindings []report.Finding
	err = json.Unmarshal(bytes, &previousFindings)
	if err != nil {
		return nil, fmt.Errorf("the format of the file %s is not supported", baselinePath)
	}

	return previousFindings, nil
}

func (d *Detector) AddBaseline(baselinePath string, source string) error {
	if baselinePath != "" {
		absoluteSource, err := filepath.Abs(source)
		if err != nil {
			return err
		}

		absoluteBaseline, err := filepath.Abs(baselinePath)
		if err != nil {
			return err
		}

		relativeBaseline, err := filepath.Rel(absoluteSource, absoluteBaseline)
		if err != nil {
			return err
		}

		baseline, err := LoadBaseline(baselinePath)
		if err != nil {
			return err
		}

		d.baseline = baseline
		baselinePath = relativeBaseline

	}

	d.baselinePath = baselinePath
	return nil
}
